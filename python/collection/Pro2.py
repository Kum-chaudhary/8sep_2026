l1 = [10,20,45,67,90,70]
"""
0   1   2   3   4   5   (+) positive indexing
10  20  45  67  90  70
-6 -5  -4  -3   -2  -1  (-) negative indexing
"""
# slicing 

print(l1[0:2]) # first 2 item print [10,20]

print(l1[4:6]) # last 2 element from list [90,70]

print(l1[-5::]) # -5 se -1 tak 

print(l1[-6:-4]) # [10,20]

print(l1[-3:]) # -3 se -1

