"""
tuple : is a collection data type.
       tuple which is represent by () braces.
       tuple is a orderable,indexable,sequence data type 
       but tuple is an inmutable datatype.
 
"""
t = ()
print(t) #()

t = 10,20,30,40,50
print(t)  #(10,20,30,40,50)
print(type(t)) #tuple


t = (100)
print(t)  #100
print(type(t)) # int
  
t = (100,) 
print(t) # (100,)
print(type(t)) #tuple